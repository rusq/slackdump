-- +goose Up
-- Not STRICT: SQLite before 3.37 rejects the whole schema for STRICT tables.
-- KEY1 has no declared type, so values keep their storage class.
CREATE TABLE DEDUPE_CHECKPOINT (
    ID              INTEGER PRIMARY KEY CHECK (ID = 1),
    MODE            TEXT    NOT NULL CHECK (MODE IN ('exact', 'message-key')),
    OWNER           TEXT    NOT NULL,
    ENTITY          INTEGER NOT NULL CHECK (ENTITY IN (0, 2, 3, 4, 5)),
    KEY1                    NOT NULL,
    KEY2            TEXT    NOT NULL,
    MESSAGES        INTEGER NOT NULL,
    CANVAS_MESSAGES INTEGER NOT NULL,
    USERS           INTEGER NOT NULL,
    CHANNELS        INTEGER NOT NULL,
    CHANNEL_USERS   INTEGER NOT NULL,
    FILES           INTEGER NOT NULL,
    CHUNKS          INTEGER NOT NULL,
    ROWS_EXAMINED     INTEGER NOT NULL,
    BATCHES_COMMITTED INTEGER NOT NULL,
    CHECK ((ENTITY = 0 AND typeof(KEY1) = 'integer') OR (ENTITY <> 0 AND typeof(KEY1) = 'text'))
);

-- Normal writers insert the chunk and its payload in the same transaction.
-- Track changes to chunk eligibility and session precedence as well.
-- +goose StatementBegin
CREATE TRIGGER DEDUPE_RESET_CHUNK_INSERT AFTER INSERT ON CHUNK
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
CREATE TRIGGER DEDUPE_RESET_CHUNK_DELETE AFTER DELETE ON CHUNK
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
CREATE TRIGGER DEDUPE_RESET_CHUNK_UPDATE AFTER UPDATE OF ID, SESSION_ID, TYPE_ID ON CHUNK
WHEN OLD.ID IS NOT NEW.ID OR OLD.SESSION_ID IS NOT NEW.SESSION_ID OR OLD.TYPE_ID IS NOT NEW.TYPE_ID
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
CREATE TRIGGER DEDUPE_RESET_SESSION_INSERT AFTER INSERT ON SESSION
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
CREATE TRIGGER DEDUPE_RESET_SESSION_DELETE AFTER DELETE ON SESSION
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
CREATE TRIGGER DEDUPE_RESET_SESSION_UPDATE AFTER UPDATE OF ID, FINISHED ON SESSION
WHEN OLD.ID IS NOT NEW.ID OR OLD.FINISHED IS NOT NEW.FINISHED
BEGIN
    DELETE FROM DEDUPE_CHECKPOINT WHERE ID = 1;
END;
-- +goose StatementEnd

-- +goose Down
DROP TRIGGER DEDUPE_RESET_SESSION_UPDATE;
DROP TRIGGER DEDUPE_RESET_SESSION_DELETE;
DROP TRIGGER DEDUPE_RESET_SESSION_INSERT;
DROP TRIGGER DEDUPE_RESET_CHUNK_UPDATE;
DROP TRIGGER DEDUPE_RESET_CHUNK_DELETE;
DROP TRIGGER DEDUPE_RESET_CHUNK_INSERT;
DROP TABLE DEDUPE_CHECKPOINT;
